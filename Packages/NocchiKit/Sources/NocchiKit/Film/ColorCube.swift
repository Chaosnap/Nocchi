import Foundation

/// Core Image `CIColorCubeWithColorSpace` 需要的立方体数据：
/// RGBA Float32，R 变化最快，其次 G，最后 B（与 `.cube` 文件顺序一致）。
public struct ColorCube: Equatable, Sendable {
    public let dimension: Int
    public let values: [Float]

    public init(dimension: Int, values: [Float]) {
        precondition(dimension >= 2, "cube dimension must be >= 2")
        precondition(values.count == dimension * dimension * dimension * 4, "cube value count mismatch")
        self.dimension = dimension
        self.values = values
    }

    /// 直接交给 Core Image 的字节数据。
    public var data: Data {
        values.withUnsafeBufferPointer { Data(buffer: $0) }
    }

    /// 按函数逐格点生成立方体。
    public static func make(dimension: Int, _ transform: (RGB) -> RGB) -> ColorCube {
        let n = max(2, dimension)
        var values = [Float](repeating: 0, count: n * n * n * 4)
        let scale = 1 / Float(n - 1)
        var i = 0
        for b in 0..<n {
            for g in 0..<n {
                for r in 0..<n {
                    let out = transform(RGB(Float(r) * scale, Float(g) * scale, Float(b) * scale))
                    values[i] = out.x
                    values[i + 1] = out.y
                    values[i + 2] = out.z
                    values[i + 3] = 1
                    i += 4
                }
            }
        }
        return ColorCube(dimension: n, values: values)
    }

    public static func identity(dimension: Int = 17) -> ColorCube {
        make(dimension: dimension) { $0 }
    }

    /// 取格点值。
    public func entry(r: Int, g: Int, b: Int) -> RGB {
        let n = dimension
        let i = ((b * n + g) * n + r) * 4
        return RGB(values[i], values[i + 1], values[i + 2])
    }

    /// 三线性插值查表（用于测试与 CPU 侧取色）。
    public func lookup(_ color: RGB) -> RGB {
        let n = dimension
        let maxIndex = Float(n - 1)
        let p = ColorMath.clamp01(color) * maxIndex
        let r0 = min(Int(p.x), n - 1), g0 = min(Int(p.y), n - 1), b0 = min(Int(p.z), n - 1)
        let r1 = min(r0 + 1, n - 1), g1 = min(g0 + 1, n - 1), b1 = min(b0 + 1, n - 1)
        let fr = p.x - Float(r0), fg = p.y - Float(g0), fb = p.z - Float(b0)

        let c00 = entry(r: r0, g: g0, b: b0) * (1 - fr) + entry(r: r1, g: g0, b: b0) * fr
        let c10 = entry(r: r0, g: g1, b: b0) * (1 - fr) + entry(r: r1, g: g1, b: b0) * fr
        let c01 = entry(r: r0, g: g0, b: b1) * (1 - fr) + entry(r: r1, g: g0, b: b1) * fr
        let c11 = entry(r: r0, g: g1, b: b1) * (1 - fr) + entry(r: r1, g: g1, b: b1) * fr
        let c0 = c00 * (1 - fg) + c10 * fg
        let c1 = c01 * (1 - fg) + c11 * fg
        return c0 * (1 - fb) + c1 * fb
    }

    /// 与恒等映射按强度混合（滤镜强度滑块）。
    public func withIntensity(_ intensity: Float) -> ColorCube {
        let k = ColorMath.clamp01(intensity)
        guard k < 0.9999 else { return self }
        let n = dimension
        let scale = 1 / Float(n - 1)
        var out = values
        var i = 0
        for b in 0..<n {
            for g in 0..<n {
                for r in 0..<n {
                    let identity = RGB(Float(r) * scale, Float(g) * scale, Float(b) * scale)
                    let v = RGB(values[i], values[i + 1], values[i + 2])
                    let m = ColorMath.mix(identity, v, k)
                    out[i] = m.x
                    out[i + 1] = m.y
                    out[i + 2] = m.z
                    i += 4
                }
            }
        }
        return ColorCube(dimension: n, values: out)
    }

    /// 序列化为 `.cube` 文本（可以把自己的胶卷导出给其他软件用）。
    public func cubeText(title: String) -> String {
        var lines: [String] = []
        lines.reserveCapacity(dimension * dimension * dimension + 4)
        lines.append("TITLE \"\(title.replacingOccurrences(of: "\"", with: "'"))\"")
        lines.append("# Generated by Nocchi \(NocchiKit.version)")
        lines.append("LUT_3D_SIZE \(dimension)")
        lines.append("DOMAIN_MIN 0.0 0.0 0.0")
        lines.append("DOMAIN_MAX 1.0 1.0 1.0")
        var i = 0
        while i < values.count {
            lines.append(String(format: "%.6f %.6f %.6f", values[i], values[i + 1], values[i + 2]))
            i += 4
        }
        return lines.joined(separator: "\n") + "\n"
    }
}

public extension ColorCube {
    /// 所有格点都是有限数并且落在 0…1（检查烘焙结果用）。
    var isWellFormed: Bool {
        values.allSatisfy { $0.isFinite && $0 >= 0 && $0 <= 1 }
    }
}

/// 把色调配方烘焙成立方体。
public enum LUTBaker {
    /// 默认格点数：33³ 在质量与内存（约 575 KB）之间平衡。
    public static let defaultDimension = 33

    public static func bake(_ recipe: ToneRecipe, dimension: Int = defaultDimension, intensity: Float = 1) -> ColorCube {
        // 配方只预处理一次（解析颜色、曲线切线、色相带），每个格点复用。
        let program = ToneProgram(recipe)
        return ColorCube.make(dimension: dimension) { program.apply($0) }.withIntensity(intensity)
    }
}
